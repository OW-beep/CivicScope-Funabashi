// 将来的にアクセス解析（Vercel Analytics等）を導入した際は、実データに基づく
// ランキングに置き換えることを想定しています。
export function getFeaturedArticles(count = 3) {
  const featured = articles.filter((a) => a.featured);
  return featured.slice(0, count);
}

export function getArticleBySlug(slug) {
  return articles.find((a) => a.slug === slug) || null;
}

// 同じタグの記事を優先しつつ、指定件数だけ「あわせて読みたい」記事を返す。
// 同タグが足りない場合は新着順で補う。
export function getRelatedArticles(slug, count = 2) {
  const current = getArticleBySlug(slug);
  if (!current) return [];
  const rest = getArticlesSortedByDate().filter((a) => a.slug !== slug);
  const sameTag = rest.filter((a) => a.tag === current.tag);
  const others = rest.filter((a) => a.tag !== current.tag);
  return [...sameTag, ...others].slice(0, count);
}

// 新しい記事が配列の最後に追記されていっても、一覧では常に新着順（日付降順）で
// 表示されるようにするためのヘルパー。日付が同じ場合は元の並び順を保つ。
export function getArticlesSortedByDate() {
  return [...articles].sort((a, b) => new Date(b.date) - new Date(a.date));
}
